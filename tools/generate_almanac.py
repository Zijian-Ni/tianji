"""Rebuild both offline almanacs: python tools/generate_almanac.py /path/to/de440s.bsp

Development only: pip install skyfield==1.54
Ephemeris: https://ssd.jpl.nasa.gov/ftp/eph/planets/bsp/de440s.bsp
"""

import argparse
import json
from bisect import bisect_left, bisect_right
from collections import defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

from skyfield import almanac, almanac_east_asia
from skyfield.api import load, load_file

ROOT = Path(__file__).resolve().parents[1]

# Match the published civil lunar calendar when a new moon falls near
# midnight. The solar-term instants below continue to use the ephemeris.
# Source: Hong Kong Observatory, https://www.hko.gov.hk/en/gts/time/conversion.htm
HKO_MONTH_STARTS = {
    date(1914, 11, 18): date(1914, 11, 17),
    date(1916, 2, 4): date(1916, 2, 3),
    date(1920, 11, 11): date(1920, 11, 10),
    date(2057, 9, 29): date(2057, 9, 28),
    date(2097, 8, 8): date(2097, 8, 7),
}


def civil_time(time):
    # UT1 + 8h extends standard Beijing time to years before UTC and uses
    # Skyfield's Earth rotation model for years without known leap seconds.
    return time.utc_datetime().replace(tzinfo=None) + timedelta(hours=8, seconds=float(time.dut1))


def lunar_years(new_moons, major_terms, solstices):
    """Month 11 contains the winter solstice. In a 13-month solstice year,
    the first month without a major solar term repeats the preceding number.
    Membership is determined by civil dates, including the whole new-moon day.
    """
    rows = defaultdict(list)
    winter_months = [bisect_right(new_moons, day) - 1 for day in solstices]
    year = solstices[0].year
    for first, end in zip(winter_months, winter_months[1:]):
        month = 10
        needs_leap = end - first == 13
        for i in range(first, end):
            start, stop = new_moons[i : i + 2]
            leap = needs_leap and bisect_left(major_terms, start) == bisect_left(major_terms, stop)
            if leap:
                needs_leap = False
            else:
                month = month % 12 + 1
                if month == 1:
                    year = start.year
                    if year == 1900:
                        assert start == datetime(1900, 1, 31).date()
            days = (stop - start).days
            assert days in (29, 30)
            rows[year].append(-days if leap else days)
        assert not needs_leap
    result = [rows[year] for year in range(1900, 2101)]
    assert all(sum(length > 0 for length in row) == 12 for row in result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ephemeris")
    ephemeris = load_file(parser.parse_args().ephemeris)
    timescale = load.timescale()
    terms = almanac_east_asia.solar_terms(ephemeris)
    phases = almanac.moon_phases(ephemeris)
    term_rows, new_moons, major_terms, solstices = [], [], [], []
    for year in range(1898, 2103):
        start, stop = timescale.utc(year, 1, 1), timescale.utc(year + 1, 1, 1)
        times, indices = almanac.find_discrete(start, stop, terms)
        assert list(indices) == [(19 + n) % 24 for n in range(24)]  # January starts at 285°.
        offsets = []
        for time, index in zip(times, indices):
            civil = civil_time(time)
            if index % 2 == 0:
                major_terms.append(civil.date())
            if index == 18:  # Winter solstice, 270°
                solstices.append(civil.date())
            rounded = (civil + timedelta(seconds=30)).replace(second=0, microsecond=0)
            offsets.append(int((rounded - datetime(year, 1, 1)).total_seconds() // 60))
        if 1899 <= year <= 2101:
            term_rows.append(offsets)
        times, indices = almanac.find_discrete(start, stop, phases)
        for time in times[indices == 0]:
            day = civil_time(time).date()
            new_moons.append(HKO_MONTH_STARTS.get(day, day))

    def array(rows):
        return "[\n" + ",\n".join("  " + json.dumps(row, separators=(",", ":")) for row in rows) + "\n]"

    data = '{"termStart":1899,"termMinutes":' + array(term_rows)
    data += ',"lunarStart":"1900-01-31","lunarMonths":' + array(lunar_years(new_moons, major_terms, solstices)) + "}"
    (ROOT / "src/tianji/calendar/almanac.json").write_text(data + "\n", encoding="ascii")
    js = "// Generated by tools/generate_almanac.py (Skyfield / JPL DE440s).\n"
    js += "const TianjiAlmanac = " + data + ";\n"
    js += "if (typeof module !== 'undefined' && module.exports) module.exports = TianjiAlmanac;\n"
    (ROOT / "web/js/almanac.js").write_text(js, encoding="ascii")


if __name__ == "__main__":
    main()
